/**
 * One writer for the generated Lab data, shared by the build pipeline and the
 * link checker. Keeping it in one place matters because the link checker may
 * rewrite the file after it drops a dead URL.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const GENERATED_DIR = resolve(ROOT, 'src/generated');
export const GENERATED_JSON = resolve(GENERATED_DIR, 'lab.json');
export const GENERATED_TS = resolve(GENERATED_DIR, 'lab.ts');

export function writeLabData(data) {
  mkdirSync(GENERATED_DIR, { recursive: true });
  const json = `${JSON.stringify(data, null, 2)}\n`;
  writeFileSync(GENERATED_JSON, json);
  writeFileSync(
    GENERATED_TS,
    `/* Generated by scripts/lab.mjs. Do not edit by hand. */\n` +
      `import type { LabData } from '../lab/types';\n\n` +
      `export const labData: LabData = ${json.trim()};\n`,
  );
}
